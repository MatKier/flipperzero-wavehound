#!/usr/bin/env python3
"""Build the Wavehound Flipper app with the vendor database bundled in.

The vendor database is committed: flipper_app/assets/oui.db, generated by
tools/gen_oui.py from the Wireshark manuf in tools/manuf.gz. application.fam
bundles the assets folder (fap_file_assets="assets") and the Flipper unpacks it
to /ext/apps_assets/wavehound/oui.db. A plain build just uses it; refreshing it
rewrites both files, which then get committed together (CI checks they match).

Usage:
  python3 build_app.py                     # build with the committed oui.db
  python3 build_app.py --update-db         # download the latest manuf, regenerate, then build
  python3 build_app.py --manuf path/to/manuf.gz  # regenerate from a local manuf.gz instead
  python3 build_app.py --update-db --no-build  # only refresh the db
  python3 build_app.py --launch            # build, then upload+run on a connected Flipper
  python3 build_app.py -- --target f7 ...  # args after -- are passed to ufbt

Needs ufbt on PATH (https://github.com/flipperdevices/flipperzero-ufbt) and,
for --update-db, network access.
"""

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
APP_DIR = ROOT / "flipper_app"
ASSETS_DIR = APP_DIR / "assets"
DB_PATH = ASSETS_DIR / "oui.db"
GEN = ROOT / "tools" / "gen_oui.py"
MANUF_GZ = ROOT / "tools" / "manuf.gz"


def run(cmd, cwd=None):
    print("+ " + " ".join(str(c) for c in cmd), file=sys.stderr)
    subprocess.run(cmd, cwd=cwd, check=True)


def build_db(manuf):
    """Regenerate oui.db and keep the manuf it came from in tools/manuf.gz."""
    ASSETS_DIR.mkdir(parents=True, exist_ok=True)
    if manuf:
        manuf = Path(manuf).resolve()
        if manuf.suffix != ".gz":
            sys.exit("--manuf takes Wireshark's manuf.gz as downloaded (it's committed as-is)")
        if manuf != MANUF_GZ:
            shutil.copyfile(manuf, MANUF_GZ)
        cmd = [sys.executable, str(GEN), str(MANUF_GZ)]
    else:
        cmd = [sys.executable, str(GEN), "--download", "--save-manuf", str(MANUF_GZ)]
    run(cmd + ["-o", str(DB_PATH)])


def build_fap(ufbt, launch, extra):
    exe = shutil.which(ufbt)
    if not exe:
        sys.exit(
            f"'{ufbt}' not found on PATH. Install it with "
            "'pipx install ufbt' (see flipperzero-ufbt), or pass --no-build."
        )
    # `ufbt launch` builds, uploads the .fap to a connected Flipper and runs it;
    # plain `ufbt` just builds.
    cmd = [exe] + (["launch"] if launch else []) + list(extra)
    run(cmd, cwd=APP_DIR)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument(
        "--update-db",
        action="store_true",
        help="download the latest Wireshark manuf into tools/manuf.gz and regenerate oui.db",
    )
    ap.add_argument("--manuf", help="regenerate oui.db from this local manuf.gz instead")
    ap.add_argument("--no-build", action="store_true", help="skip ufbt (e.g. only refresh the db)")
    ap.add_argument(
        "--launch",
        action="store_true",
        help="after building, upload the .fap to a connected Flipper and run it (ufbt launch)",
    )
    ap.add_argument("--ufbt", default="ufbt", help="ufbt command (default: ufbt)")
    ap.add_argument("ufbt_args", nargs="*", help="args passed through to ufbt (after --)")
    args = ap.parse_args()

    if args.update_db or args.manuf:
        build_db(args.manuf)
    elif not DB_PATH.exists():
        print(f"warning: {DB_PATH} does not exist; the app will show vendors as Unknown", file=sys.stderr)

    if not args.no_build:
        build_fap(args.ufbt, args.launch, args.ufbt_args)

    print("Done.", file=sys.stderr)


if __name__ == "__main__":
    main()
