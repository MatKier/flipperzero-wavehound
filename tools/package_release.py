#!/usr/bin/env python3
"""Collect a Wavehound release into one folder (used by .github/workflows/release.yml).

Run after `python3 build_app.py --manuf manuf` and `pio run -d firmware`:

    python3 tools/package_release.py --manuf manuf.gz -o dist --notes release-notes.md

It produces, in the output folder:

    wavehound.fap                         Flipper app with oui.db bundled
    wavehound-esp32s2-fw<N>-full.bin      merged board image, flash at 0x0
    wavehound-esp32s2-fw<N>-bootloader.bin / -partitions.bin / -app.bin
    FLASHING.txt                          offsets + esptool commands
    THIRD_PARTY_NOTICES.md                repo notices + build details
    wavehound-licenses.zip                LICENSE, notices and license texts
    manuf.gz                              the Wireshark data oui.db was built from

Flash offsets and settings come from the build's flasher_args.json, so a
partition change can't silently ship wrong offsets. License texts are copied
from the exact ESP-IDF/toolchain packages PlatformIO used; a missing one fails
the run, so an ESP-IDF update that moves files gets noticed.
"""

import argparse
import gzip
import json
import os
import re
import shutil
import subprocess
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP_DIR = ROOT / "flipper_app"
FIRMWARE_DIR = ROOT / "firmware"
BUILD_DIR = FIRMWARE_DIR / ".pio" / "build" / "flipper_wifi_devboard"
FAP = APP_DIR / "dist" / "wavehound.fap"
OUI_DB = APP_DIR / "assets" / "oui.db"
CHANGELOG = APP_DIR / "catalog" / "changelog.md"

PIO_HOME = Path(os.environ.get("PLATFORMIO_CORE_DIR", Path.home() / ".platformio"))
IDF_DIR = PIO_HOME / "packages" / "framework-espidf"
TOOLCHAIN_DIR = PIO_HOME / "packages" / "toolchain-xtensa-esp-elf"
PLATFORM_JSON = PIO_HOME / "platforms" / "espressif32" / "platform.json"
UFBT_STATE = Path(os.environ.get("UFBT_HOME", Path.home() / ".ufbt")) / "current" / "ufbt_state.json"

# flasher_args.json names the ESP-IDF build outputs; PlatformIO copies them to
# the build root under its own names.
PIO_IMAGES = {
    "bootloader": ("bootloader.bin", "bootloader"),
    "partition-table": ("partitions.bin", "partitions"),
    "app": ("firmware.bin", "app"),
}

# (license file in the release, source dir, path inside it)
LICENSES = [
    ("ESP-IDF-LICENSE.txt", IDF_DIR, "LICENSE"),
    ("esp_wifi-lib-LICENSE.txt", IDF_DIR, "components/esp_wifi/lib/LICENSE"),
    ("esp_phy-lib-LICENSE.txt", IDF_DIR, "components/esp_phy/lib/LICENSE"),
    ("esp_coex-lib-LICENSE.txt", IDF_DIR, "components/esp_coex/lib/LICENSE"),
    ("FreeRTOS-Kernel-LICENSE.md", IDF_DIR, "components/freertos/FreeRTOS-Kernel/LICENSE.md"),
    ("lwIP-COPYING.txt", IDF_DIR, "components/lwip/lwip/COPYING"),
    ("wpa_supplicant-COPYING.txt", IDF_DIR, "components/wpa_supplicant/COPYING"),
    ("wpa_supplicant-README.txt", IDF_DIR, "components/wpa_supplicant/README"),
    ("MbedTLS-LICENSE.txt", IDF_DIR, "components/mbedtls/mbedtls/LICENSE"),
    ("TF-PSA-Crypto-LICENSE.txt", IDF_DIR, "components/mbedtls/mbedtls/tf-psa-crypto/LICENSE"),
    ("esp_libc-COPYING.NEWLIB.txt", IDF_DIR, "components/esp_libc/COPYING.NEWLIB"),
    ("esp_libc-COPYING.picolibc.txt", IDF_DIR, "components/esp_libc/COPYING.picolibc"),
    ("picolibc-COPYING.picolibc.txt", TOOLCHAIN_DIR, "share/licenses/picolibc/COPYING.picolibc"),
    ("picolibc-COPYING.NEWLIB.txt", TOOLCHAIN_DIR, "share/licenses/picolibc/COPYING.NEWLIB"),
    ("GCC-COPYING.RUNTIME.txt", TOOLCHAIN_DIR, "share/licenses/gcc/COPYING.RUNTIME"),
    ("GCC-COPYING3.txt", TOOLCHAIN_DIR, "share/licenses/gcc/COPYING3"),
    # Wireshark (source of oui.db) is GPL-2.0-or-later; this is the stock GPLv2 text.
    ("GPL-2.0.txt", TOOLCHAIN_DIR, "share/licenses/picolibc/COPYING.GPL2"),
]


def fail(msg):
    sys.exit(f"package_release: {msg}")


def read_match(path, pattern, what):
    m = re.search(pattern, path.read_text(), re.M)
    if not m:
        fail(f"can't find {what} in {path}")
    return m.group(1)


def read_json_field(path, field):
    try:
        return json.loads(path.read_text())[field]
    except (OSError, ValueError, KeyError):
        return "unknown"


def manuf_source(manuf):
    """'TShark <version>, <date>' for the manuf: the header names the build that
    generated it, and the gzip header carries when (the release may use a cached copy)."""
    opener = gzip.open if manuf.suffix == ".gz" else open
    with opener(manuf, "rb") as f:
        m = re.search(r"generated by (TShark \S+)", f.read(2048).decode("utf-8", "replace"))
        mtime = getattr(f, "mtime", None)
    when = datetime.fromtimestamp(mtime, timezone.utc).date().isoformat() if mtime else "date unknown"
    return f"{m.group(1) if m else 'unknown TShark'}, {when}"


def flash_layout():
    """Return (chip, settings dict, [(offset, pio file, suffix)]) from flasher_args.json."""
    args = json.loads((BUILD_DIR / "flasher_args.json").read_text())
    images = []
    for role, (pio_name, suffix) in PIO_IMAGES.items():
        if role not in args:
            fail(f"flasher_args.json has no '{role}' image")
        images.append((args[role]["offset"], BUILD_DIR / pio_name, suffix))
    offsets = {int(o, 16) for o in args["flash_files"]}
    if offsets != {int(o, 16) for o, _, _ in images}:
        fail(f"flasher_args.json flashes {sorted(args['flash_files'])}; update PIO_IMAGES")
    for _, path, _ in images:
        if not path.exists():
            fail(f"missing {path} (run `pio run -d firmware` first)")
    return args["extra_esptool_args"]["chip"], args["flash_settings"], sorted(images, key=lambda i: int(i[0], 16))


def esptool_cmd():
    # PlatformIO's own esptool (the one `pio run -t upload` uses); run from the project dir.
    return ["pio", "pkg", "exec", "-p", "tool-esptool", "--", "esptool"]


def flashing_txt(chip, s, images, names, full):
    parts = " \\\n    ".join(f"{off} {names[suffix]}" for off, _, suffix in images)
    table = "\n".join(f"  {off:<8} {names[suffix]}" for off, _, suffix in images)
    return f"""Wavehound board firmware ({chip}, {s['flash_size']} flash)

Put the dev board in download mode: hold BOOT, tap RESET, release BOOT, and
connect it with its own USB-C port. Replace PORT with its serial port (not the
Flipper's). Tap RESET afterwards to boot the new firmware.

Easiest: flash the merged image at 0x0 (works coming from any other firmware):

  esptool --chip {chip} -p PORT write-flash 0x0 {full}

Or the three separate images (same result):

{table}

  esptool --chip {chip} -p PORT write-flash --flash-mode {s['flash_mode']} \\
    --flash-freq {s['flash_freq']} --flash-size {s['flash_size']} \\
    {parts}

Updating an existing Wavehound install: flashing just the app image usually
works, as long as the partition table did not change:

  esptool --chip {chip} -p PORT write-flash {images[-1][0]} {names['app']}

(esptool v4 spells the command write_flash and the options --flash_mode etc.)
"""


def release_notes(version, fw, full):
    text = CHANGELOG.read_text()
    m = re.search(rf"^## v{re.escape(version)}\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not m:
        fail(f"no '## v{version}' entry in {CHANGELOG}")
    return (
        m.group(1).strip()
        + f"\n\n---\n\nBoard firmware v{fw}. Copy `wavehound.fap` to `SD:/apps/GPIO/ESP/`; "
        f"flash `{full}` to the dev board at 0x0 (see `FLASHING.txt`). "
        "Third-party licenses: `THIRD_PARTY_NOTICES.md` and `wavehound-licenses.zip`.\n"
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manuf", required=True, type=Path, help="the manuf (or manuf.gz) oui.db was built from")
    ap.add_argument("-o", "--out", default="dist", type=Path, help="output folder (default: dist)")
    ap.add_argument("--notes", type=Path, help="also write GitHub release notes here")
    args = ap.parse_args()

    version = read_match(APP_DIR / "application.fam", r'^\s*fap_version="([^"]+)"', "fap_version")
    fw = read_match(FIRMWARE_DIR / "main" / "proto.h", r'^#define WH_FW_VERSION "([^"]+)"', "WH_FW_VERSION")
    for path, hint in ((FAP, "build the app first"), (OUI_DB, "the .fap would ship without vendors")):
        if not path.exists():
            fail(f"missing {path} ({hint})")

    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)

    shutil.copy2(FAP, out / "wavehound.fap")

    chip, settings, images = flash_layout()
    names = {suffix: f"wavehound-{chip}-fw{fw}-{suffix}.bin" for _, _, suffix in images}
    for _, path, suffix in images:
        shutil.copy2(path, out / names[suffix])
    full = f"wavehound-{chip}-fw{fw}-full.bin"
    subprocess.run(
        esptool_cmd()
        + ["--chip", chip, "merge-bin", "-o", str(out / full),
           "--flash-mode", settings["flash_mode"], "--flash-freq", settings["flash_freq"],
           "--flash-size", settings["flash_size"]]
        + [str(a) for off, path, _ in images for a in (off, path)],
        cwd=FIRMWARE_DIR,
        check=True,
    )
    (out / "FLASHING.txt").write_text(flashing_txt(chip, settings, images, names, full))

    # The exact Wireshark data oui.db came from (GPL "corresponding source").
    if args.manuf.suffix == ".gz":
        shutil.copy2(args.manuf, out / "manuf.gz")
    else:
        with open(args.manuf, "rb") as src, gzip.open(out / "manuf.gz", "wb") as dst:
            shutil.copyfileobj(src, dst)

    try:
        sha = os.environ.get("GITHUB_SHA") or subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        sha = "unknown"
    notices = (ROOT / "THIRD_PARTY_NOTICES.md").read_text().rstrip() + f"""

## Build details

- Wavehound app v{version}, board firmware v{fw}, commit `{sha}`
- Flipper firmware SDK: {read_json_field(UFBT_STATE, "version")}
- PlatformIO espressif32 platform: {read_json_field(PLATFORM_JSON, "version")}
- ESP-IDF: {(IDF_DIR / "version.txt").read_text().strip()}
- Toolchain (toolchain-xtensa-esp-elf): {read_json_field(TOOLCHAIN_DIR / "package.json", "version")}
- OUI data (`manuf.gz`): Wireshark manuf generated by {manuf_source(args.manuf)}
"""
    (out / "THIRD_PARTY_NOTICES.md").write_text(notices)

    with zipfile.ZipFile(out / "wavehound-licenses.zip", "w", zipfile.ZIP_DEFLATED) as z:
        z.write(ROOT / "LICENSE", "LICENSE")
        z.writestr("THIRD_PARTY_NOTICES.md", notices)
        for name, base, rel in LICENSES:
            src = base / rel
            if not src.exists():
                fail(f"missing license file {src}; update LICENSES (and THIRD_PARTY_NOTICES.md)")
            z.write(src, f"licenses/{name}")

    if args.notes:
        args.notes.write_text(release_notes(version, fw, full))

    for f in sorted(out.iterdir()):
        print(f"{f.stat().st_size:>9}  {f.name}")


if __name__ == "__main__":
    main()
